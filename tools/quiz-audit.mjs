// Audit the quiz's wrong options. Read-only: it never writes inside the repo.
// Usage: node tools/quiz-audit.mjs
// Prints only the weak-word count and the report path.
import fs from 'fs';
import os from 'os';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const QCORE = require(path.join(ROOT, 'public', 'quiz-core.js'));
const seo = require(path.join(ROOT, 'shared', 'seo.js'));
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'public', 'words.json'), 'utf8'));

const DRAWS = 500;
const SUHAH = (surah) => QCORE.SURAH_NO[seo.SURAH_SLUG[String(surah).split(/\s+/).pop()]] || 0;
const pool = QCORE.buildPool(data, SUHAH);

// A fixed seed keeps the report reproducible run to run.
function rng(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng(20250917);
const rows = pool.map((t) => {
  const tk = QCORE.nrm(t.mean);
  const tl = tk.length;
  let longest = 0;
  let ovSum = 0;
  for (let i = 0; i < DRAWS; i++) {
    const d = QCORE.pickDistractors(t, pool, 3, rand);
    let dmax = 0;
    for (const x of d) {
      dmax = Math.max(dmax, QCORE.nrm(x.mean).length);
      ovSum += QCORE.overlap(tk, x.mean) / (d.length || 1);
    }
    if (tl > dmax) longest++;
  }
  return {
    id: t.id,
    sn: t.sn,
    sname: t.sname,
    word: t.word,
    mean: t.mean,
    longest: (longest / DRAWS) * 100,
    ov: ovSum / DRAWS,
  };
});

const sorted = rows.map((r) => r.ov).sort((a, b) => a - b);
const median = sorted.length % 2
  ? sorted[(sorted.length - 1) / 2]
  : (sorted[sorted.length / 2 - 1] + sorted[sorted.length / 2]) / 2;
const weak = rows.filter((r) => r.longest > 40 || r.ov < median);

const lines = [];
lines.push('# Quiz weak questions');
lines.push('');
lines.push('Generated by `tools/quiz-audit.mjs` (read-only, ' + DRAWS + ' draws per word, fixed seed).');
lines.push('A word is weak when the correct meaning is the longest option in more than 40% of');
lines.push('draws, or when its average distractor token overlap is below the median (' + median.toFixed(3) + ').');
lines.push('');
lines.push('- words audited: ' + rows.length);
lines.push('- weak words: ' + weak.length);
lines.push('');
for (const r of weak) {
  const why = [];
  if (r.longest > 40) why.push('longest ' + r.longest.toFixed(1) + '%');
  if (r.ov < median) why.push('overlap ' + r.ov.toFixed(3));
  lines.push('## ' + r.id + ' - surah ' + r.sn);
  lines.push('');
  lines.push('- weak because: ' + why.join(', '));
  lines.push('- correct longest: ' + r.longest.toFixed(1) + '% of draws');
  lines.push('- avg distractor token overlap: ' + r.ov.toFixed(3));
  lines.push('- word: ' + r.word);
  lines.push('- meaning: ' + r.mean);
  lines.push('');
}

const dir = path.join(process.env.USERPROFILE || os.homedir(), 'ghareeb-backups');
fs.mkdirSync(dir, { recursive: true });
const out = path.join(dir, 'quiz-weak-questions.md');
fs.writeFileSync(out, lines.join('\n'), 'utf8');

console.log('WEAK=' + weak.length);
console.log('REPORT=' + out);
